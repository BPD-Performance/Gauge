static inline const DotGlyph *dotFind(char c)
{
  if (c >= 'a' && c <= 'z') c = c - 'a' + 'A';          // lower case draws as upper case
  for (size_t i = 0; i < sizeof(DOT_FONT) / sizeof(DOT_FONT[0]); i++)
    if (DOT_FONT[i].c == c) return &DOT_FONT[i];
  for (size_t i = 0; i < sizeof(DOT_FONT) / sizeof(DOT_FONT[0]); i++)
    if (DOT_FONT[i].c == '?') return &DOT_FONT[i];
  return &DOT_FONT[0];
}
